package com.kidstv.kiosk

import java.util.UUID

/**
 * 「这一次进程活到第几代」。
 *
 * 用来判断某个状态是不是**上一代进程**留下的，语义是"进程换过就作废"。
 *
 * 为什么需要它（v1.32）：
 * 电视待机时，系统会在息屏广播送达之前把后台进程**整批杀掉**（海信实测 13:12:40 杀进程，
 * 13:12:42 才发 `SCREEN_OFF`，我们的进程早就没了）。所以"在息屏广播里记下时刻"这条路
 * 走不通 —— 代码根本没机会执行，`commit()` 永远落不了盘。
 *
 * ⚠️ 但这**不是每次待机都会发生**（2026-11-05 实测）：同一台机器 14:04 待机、14:13 唤醒，
 * 10 分钟待机期间进程 5392 一直存活，代次没变，本判据完全没命中。那次是 `Config.heartbeat()`
 * 的"心跳空档"兜住的（tick 停了 10 分钟 > 3 分钟门槛）。
 * 所以两条判据是互补关系，缺一不可：
 *   - 长待机 / 重启 → 进程换代 → 本判据命中
 *   - 短待机 / 进程侥幸存活 → 心跳空档 → heartbeat 命中
 *
 * 更狠的反例：家长点了「临时回原桌面」，当夜待机、进程被杀，第二天早上开机，
 * 进程是全新的一代，可 `pass_once` 还是 true，看门狗第一句就 return，
 * 界面没人拉 —— 表现就是"放行后关机，开机不进儿童桌面"。
 *
 * 反过来看，这就成了一个可靠的信号：**进程换过一代 = 中间一定经历过待机或重启**。
 * 家长只是换台闪一下黑屏时，进程不会死，这一代还是这一代，放行不会被误清。
 *
 * 注意：进程活不过一次进程重启，所以这个值放内存里就够了，不用落盘。
 */
object ProcId {
    /** 本代进程的唯一标识。每次进程启动重新生成 */
    val current: String = UUID.randomUUID().toString()
}
